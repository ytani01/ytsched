def encode_line(line: str, encoding: str) -> bytes:
    """1 行を符号化する。

    :data:`BROKEN` を含む行は、そこだけ :data:`BROKEN_BYTE` に置き換える
    （utf-8 でも euc_jp でも読めないバイトを作るため）。
    """
    return BROKEN_BYTE.join(
        part.encode(encoding) for part in line.split(BROKEN)
    )


def write_file(
    relpath: str, lines: list[str], encoding: str = "utf-8"
) -> None:
    """1 ファイルを書き出す。

    最終行のうしろにも改行を付ける（旧形式の実データと同じ）。
    """
    path = OUTDIR / relpath
    path.parent.mkdir(parents=True, exist_ok=True)

    data = b"".join(encode_line(ln, encoding) + b"\n" for ln in lines)
    path.write_bytes(data)

    print(f"{relpath}: {len(lines)} 行 ({encoding}, {len(data)} バイト)")


def write_sched(
    relpath: str, sde: list[Line], encoding: str = "utf-8"
) -> None:
    """予定のファイル（タブ区切り 7 列）を書き出す。"""
    write_file(relpath, ["\t".join(ln) for ln in sde], encoding)


def clean() -> None:
    """前に生成したデータを消す。

    ``README.md`` は手で書いたものなので残す。
    """
    for path in OUTDIR.rglob("*"):
        if path.is_file() and path.name != "README.md":
            path.unlink()

    for path in sorted(OUTDIR.rglob("*"), reverse=True):
        if path.is_dir() and not any(path.iterdir()):
            path.rmdir()


def main() -> None:
    """テストデータを作り直す。"""
    OUTDIR.mkdir(parents=True, exist_ok=True)
    clean()

